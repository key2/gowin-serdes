"""LUNA SuperSpeed device on the gw_usb3 PHY — Gowin DK_USB (GW5AT-60).

The fully open USB3 Gen1 stack: LUNA's LTSSM/link/protocol/endpoint layers
drive our Amaranth GTR12 soft PHY through the width=8 PIPE adapter -- no
vendor controller netlists anywhere in the build.

    [gowin-serdes]   GTR12 Quad 0 lane 1, CPLL, 200 MHz refclk forward,
                     **5G boot trim** (Gen1-only; pclk = 125 MHz from
                     power-on, no rate change ever needed).
    [gw_usb3]        Usb31Phy(gen2=False, rate_init=0) behind
                     luna.gateware.interface.serdes_phy.GowinGTR12PIPE.
    [LUNA]           USBSuperSpeedDevice + standard control endpoint,
                     descriptors 1209:0001 (pid.codes test PID).
    [debug]          uart 0 (/dev/ttyUSB4): link-event probe;
                     uart 1 (/dev/ttyUSB5): clock/symbol probe.
                     LED = link trained (U0).

Simulation heritage: the same adapter+PHY pair passes the LFPS smoke sim
and the full raw-symbol training sim to U0
(luna/examples/usb/superspeed/gowin_gtr12_*.py).

NOTE on the CSR blob: this example boots the SerDes in the 5G trim, so
serdes.toml/serdes.csr generated here deliberately DIFFER from the
byte-pinned 10G reference configuration used by usb31-enum.

Build & program:

    python top.py                # build only (build/)
    python top.py serdes         # regenerate serdes.toml/csr only
    python top.py flash          # flash the existing bitstream
    python top.py program        # build + flash

Watch:  stty -F /dev/ttyUSB4 115200 raw -echo; cat /dev/ttyUSB4
"""

